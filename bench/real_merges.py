"""Replay real merged PRs from git history through the real squawk daemon. Offline.

    make bench-real REPOS="~/code/cognee ~/code/django"

For each recent merge where main moved while the PR was open, one checkout holds main's
side and one holds the PR's, both with HEAD at their merge base and the work unpushed,
as on two laptops. Both sides really shipped together, so a stop on a merge git took
cleanly is a false alarm, unless the merge itself had to fix something.

Each repo is cloned into a temporary folder first, so your own checkout isn't touched.
"""

import argparse
import json
import shutil
import subprocess
import tempfile
import time
from collections import Counter
from pathlib import Path

from backend.detector import check_code
from pilot.squawk import Reporter, base_commit, changed_files

RESULTS = Path(__file__).resolve().parent / "real-merges.md"
LANDING = Path(__file__).resolve().parent.parent / "frontend" / "lib" / "real-merges.json"
MOST_FILES = 40


def git(root: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", *args], cwd=root, capture_output=True, text=True, errors="replace")


def laptop(root: Path, tip: str, base: str) -> dict:
    """Put one side's work in this checkout, unpushed on top of the merge base."""
    git(root, "checkout", "-q", "-f", "--detach", tip)
    git(root, "clean", "-fdq")
    git(root, "reset", "-q", "--soft", base)
    start = base_commit(root)
    return Reporter(root).report(changed_files(root, start), start)


def concurrent(repo: Path, merge: str) -> tuple[str, str, str] | None:
    """main, the PR and their base, when both changed Python at the same time."""
    main, branch = git(repo, "rev-parse", f"{merge}^1", f"{merge}^2").stdout.split()
    bases = git(repo, "merge-base", "--all", main, branch).stdout.split()
    # Criss-cross histories have no single starting point two laptops would share.
    if len(bases) != 1 or bases[0] in (main, branch):
        return None
    sides = [git(repo, "diff", "--name-only", bases[0], tip).stdout.split() for tip in (main, branch)]
    for files in sides:
        if not files or len(files) > MOST_FILES or not any(f.endswith(".py") for f in files):
            return None
    return main, branch, bases[0]


def replay(source: Path, limit: int) -> dict:
    work = Path(tempfile.mkdtemp(prefix="detente-merges-"))
    try:
        repo = work / "clone"
        git(work, "clone", "-q", "--no-checkout", str(source), str(repo))
        left, right = work / "main", work / "pr"
        for root in (left, right):
            git(repo, "worktree", "add", "-q", "--detach", str(root), "HEAD")

        head = git(repo, "rev-parse", "--short", "HEAD").stdout.strip()
        merges = git(repo, "rev-list", "--merges", "-n", str(limit), "HEAD").stdout.split()
        rows, slowest = [], 0.0
        for number, merge in enumerate(merges, 1):
            if number % 50 == 0:
                print(f"{source.name}: {number}/{len(merges)} merges checked", flush=True)
            found = concurrent(repo, merge)
            if found is None:
                continue
            main, branch, base = found
            started = time.perf_counter()
            collisions = check_code({"main": laptop(left, main, base), "pr": laptop(right, branch, base)})
            slowest = max(slowest, time.perf_counter() - started)
            textual = git(repo, "merge-tree", "--write-tree", main, branch).returncode != 0
            rows.append({"merge": merge[:10], "textual": textual, "collisions": collisions})
        return {"name": source.name, "head": head, "merges": len(merges), "rows": rows, "slowest": slowest}
    finally:
        shutil.rmtree(work, ignore_errors=True)


def write_results(runs: list[dict]) -> str:
    lines = [
        "# Real merges",
        "",
        "Generated by `make bench-real`. Each row replays recent merges from a real project's",
        "history through the real squawk daemon on two checkouts: main's side and the PR's,",
        "both unpushed on top of their merge base. Only merges where both sides changed Python",
        f"files at the same time, with at most {MOST_FILES} files on each side, are replayed.",
        "",
        "| Project | At commit | Replayed | git conflicted | Detente stopped those | git merged cleanly | Detente stopped those | Slowest check |",
        "| --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for run in runs:
        rows = run["rows"]
        conflicted = [row for row in rows if row["textual"]]
        clean = [row for row in rows if not row["textual"]]
        lines.append(
            f"| {run['name']} | `{run['head']}` | {len(rows)} of the last {run['merges']} merges | "
            f"{len(conflicted)} | {sum(bool(row['collisions']) for row in conflicted)} | {len(clean)} | "
            f"{sum(bool(row['collisions']) for row in clean)} | {run['slowest']:.1f}s |"
        )
    false_stops = [(run["name"], row) for run in runs for row in run["rows"] if not row["textual"] and row["collisions"]]
    lines += ["", "Both sides of every merge here shipped together, so a stop on a clean merge is a", "false alarm unless the merge had to fix something.", ""]
    if false_stops:
        lines += ["Stops on clean merges, to look into:", ""]
        for name, row in false_stops:
            reasons = "; ".join(collision["reason"] for collision in row["collisions"])
            lines.append(f"- {name} `{row['merge']}`: {reasons}")
    else:
        lines.append("Detente stopped none of the clean merges.")
    kinds = Counter(c["kind"] for run in runs for row in run["rows"] for c in row["collisions"])
    lines += [
        "",
        f"Stops by kind: {', '.join(f'{kind} {count}' for kind, count in sorted(kinds.items())) or 'none'}.",
        "",
        "This measures false alarms on code that really shipped. It can't show catches git",
        "misses, because breaks like that rarely survive into a project's history; the",
        "scenarios in [results.md](results.md) cover those.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("repos", nargs="+", type=Path)
    parser.add_argument("--merges", type=int, default=300, help="recent merges to look at per repo")
    args = parser.parse_args()
    runs = [replay(repo.expanduser().resolve(), args.merges) for repo in args.repos]
    text = write_results(runs)
    RESULTS.write_text(text)
    write_landing(runs)
    print(text)


def write_landing(runs: list[dict]) -> None:
    """The landing page reads this file, so its numbers can't drift from the run."""
    projects = []
    for run in runs:
        rows = run["rows"]
        conflicted = [row for row in rows if row["textual"]]
        clean = [row for row in rows if not row["textual"]]
        projects.append(
            {
                "name": run["name"],
                "replayed": len(rows),
                "conflicted": len(conflicted),
                "caught": sum(bool(row["collisions"]) for row in conflicted),
                "clean": len(clean),
                "false_stops": sum(bool(row["collisions"]) for row in clean),
            }
        )
    LANDING.write_text(json.dumps({"projects": projects}, indent=2) + "\n")


if __name__ == "__main__":
    main()

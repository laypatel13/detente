"""Run every scenario through Detente and two baselines. Offline, no API keys.

    make bench
"""

import json
import shutil
import subprocess
import tempfile
import time
from pathlib import Path

from backend.detector import check_code, check_plan
from bench.scenarios import SCENARIOS, Edit, Scenario
from pilot.squawk import Reporter, base_commit, changed_files

ROOT = Path(__file__).resolve().parent.parent
FIXTURE = ROOT / "tests" / "fixtures" / "shoplite"
RESULTS = ROOT / "bench" / "results.md"
LANDING = ROOT / "frontend" / "lib" / "bench.json"
IDENTITY = ("-c", "user.name=bench", "-c", "user.email=bench@example.com")


def git(root: Path, *args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", *IDENTITY, *args], cwd=root, capture_output=True, text=True)


def apply(root: Path, edits: tuple[Edit, ...]) -> None:
    for path, old, new in edits:
        target = root / path
        if old:
            text = target.read_text()
            assert old in text, f"{path} doesn't contain the text this scenario edits"
            target.write_text(text.replace(old, new))
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_text(new)


def checkouts(base: Path, scenario: Scenario) -> tuple[Path, Path, Path]:
    origin = base / "origin"
    shutil.copytree(FIXTURE, origin)
    apply(origin, scenario.base)
    git(origin, "init", "-q", "-b", "main")
    git(origin, "add", "-A")
    git(origin, "commit", "-qm", "ShopLite")
    left, right = base / "a", base / "b"
    git(origin, "worktree", "add", "-q", "-b", "a", str(left))
    git(origin, "worktree", "add", "-q", "-b", "b", str(right))
    return origin, left, right


def report(root: Path) -> dict:
    base = base_commit(root)
    return Reporter(root).report(changed_files(root, base), base)


def merge_conflicts(origin: Path, left: Path, right: Path) -> bool:
    for root in (left, right):
        git(root, "add", "-A")
        git(root, "commit", "-qm", "work")
    return git(origin, "merge-tree", "--write-tree", "a", "b").returncode != 0


def lease_conflicts(scenario: Scenario) -> bool:
    return bool(set(scenario.plan_a.edit) & set(scenario.plan_b.edit))


def detente_verdict(scenario: Scenario, left: Path, right: Path) -> tuple[str, float]:
    started = time.perf_counter()
    traffic = check_plan("a", scenario.plan_a, {"b": scenario.plan_b})
    collisions = check_code({"a": report(left), "b": report(right)})
    seconds = time.perf_counter() - started
    if collisions:
        return "stop", seconds
    return ("heads-up" if traffic else "quiet"), seconds


def run(scenario: Scenario) -> dict:
    base = Path(tempfile.mkdtemp(prefix="detente-bench-"))
    try:
        origin, left, right = checkouts(base, scenario)
        apply(left, scenario.edits_a)
        apply(right, scenario.edits_b)
        verdict, seconds = detente_verdict(scenario, left, right)
        return {
            "scenario": scenario,
            "merge": merge_conflicts(origin, left, right),
            "lease": lease_conflicts(scenario),
            "detente": verdict,
            "seconds": seconds,
        }
    finally:
        shutil.rmtree(base, ignore_errors=True)


def mark(flagged: bool) -> str:
    return "flagged" if flagged else "quiet"


def write_results(rows: list[dict]) -> str:
    broken = [row for row in rows if row["scenario"].breaks]
    safe = [row for row in rows if not row["scenario"].breaks]

    def score(flag) -> tuple[int, int]:
        return sum(flag(row) for row in broken), sum(flag(row) for row in safe)

    merge_caught, merge_false = score(lambda row: row["merge"])
    lease_caught, lease_false = score(lambda row: row["lease"])
    held, held_false = score(lambda row: row["detente"] == "stop")
    warned, warned_false = score(lambda row: row["detente"] == "heads-up")
    missed = len(broken) - held - warned
    slowest = max(row["seconds"] for row in rows)
    plans_only = [
        str(index)
        for index, row in enumerate(rows, 1)
        if row["scenario"].breaks and row["detente"] == "heads-up"
    ]
    plans_only_text = (
        f"Scenarios {', '.join(plans_only)} are caught this way alone: Detente can't see "
        "those breaks in the code."
        if plans_only
        else "Every break was caught from the code."
    )

    lines = [
        "# Benchmark results",
        "",
        "Generated by `make bench`. Each scenario applies two edits to two real git checkouts",
        "of the ShopLite fixture, with neither pushed.",
        "",
        "| # | Scenario | Really breaks? | git merge-tree | File leases | Detente |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for index, row in enumerate(rows, 1):
        scenario = row["scenario"]
        lines.append(
            f"| {index} | {scenario.name} | {'yes' if scenario.breaks else 'no'} | "
            f"{mark(row['merge'])} | {mark(row['lease'])} | {row['detente']} |"
        )
    lines += [
        "",
        f"Of the {len(broken)} scenarios that really break:",
        "",
        "| Tool | Stopped from the code | Warned from plans only | Missed | Stopped safe work |",
        "| --- | --- | --- | --- | --- |",
        f"| git merge-tree | {merge_caught} | 0 | {len(broken) - merge_caught} | {merge_false} of {len(safe)} |",
        f"| File leases | {lease_caught} | 0 | {len(broken) - lease_caught} | {lease_false} of {len(safe)} |",
        f"| Detente | {held} | {warned} | {missed} | {held_false} of {len(safe)} |",
        "",
        "`stop` holds both flights because the code itself is incompatible.",
        "",
        "`heads-up` is a TRAFFIC message from the flight plans. It stops nobody, and it only",
        "exists if the agents declared the overlap honestly.",
        f"{plans_only_text} It also gave {warned_false} heads-ups on work that was fine.",
        "",
        "We wrote these scenarios ourselves to show the kinds of conflict each tool can see,",
        "so read this as a capability check, not a measure of real-world catch rates.",
        "",
        f"Slowest detection took {slowest:.3f} seconds on this machine. The squawk daemon "
        "adds up to 1 second of polling on top.",
        "",
    ]
    return "\n".join(lines)


def write_landing(rows: list[dict]) -> None:
    """The landing page's table reads this file, so its numbers can't drift from the run."""
    data = {
        "scenarios": [
            {
                "name": row["scenario"].name,
                "breaks": row["scenario"].breaks,
                "results": [mark(row["merge"]), mark(row["lease"]), row["detente"]],
            }
            for row in rows
        ]
    }
    LANDING.write_text(json.dumps(data, indent=2) + "\n")


def main() -> None:
    rows = [run(scenario) for scenario in SCENARIOS]
    text = write_results(rows)
    RESULTS.write_text(text)
    write_landing(rows)
    print(text)


if __name__ == "__main__":
    main()
